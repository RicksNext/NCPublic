function ncNormalizePathname(pathname) {
    if (!pathname) return "/";
    if (pathname === "/") return pathname;
    return pathname.endsWith("/") ? pathname : pathname + "/";
}

function ncUniqueList(items) {
    const seen = {};
    return items.filter(function(item) {
        if (!item || seen[item]) return false;
        seen[item] = true;
        return true;
    });
}

function ncGetPageProfile() {
    return NC_SEO_PAGE_PROFILES[ncNormalizePathname(window.location.pathname)] || null;
}

function ncGetDynamicSeoProfile() {
    return NC_DYNAMIC_SEO_PROFILES[ncNormalizePathname(window.location.pathname)] || null;
}

function ncGetKeywordsForPath() {
    const path = ncNormalizePathname(window.location.pathname);
    const keywords = NC_SEO_KEYWORD_CLUSTERS[path] || NC_SEO_KEYWORD_CLUSTERS.default;
    return ncUniqueList(keywords.concat(NC_SEO_KEYWORD_CLUSTERS.default));
}

function ncCleanEntityName(name) {
    if (!name) return "";
    return String(name)
        .replace(/\s+/g, " ")
        .replace(/Loading\.\.\.|Calculating\.\.\.|TBD/gi, "")
        .trim();
}

function ncGetEntityNameFromUrl(profile) {
    if (!profile || !profile.urlParam) return "";
    const params = new URLSearchParams(window.location.search);
    return ncCleanEntityName(params.get(profile.urlParam));
}

function ncApplyDynamicEntitySeo(name) {
    const profile = ncGetDynamicSeoProfile();
    const entityName = ncCleanEntityName(name);
    if (!profile || !entityName || entityName.length < 2) return;

    const safeName = entityName.startsWith("@") ? entityName : entityName;
    const title = profile.title.replace("{name}", safeName);
    const description = profile.description.replace("{name}", safeName);

    document.title = title;
    ncSetMetaByAttribute("name", "description", description);
    ncSetMetaByAttribute("name", "twitter:title", title);
    ncSetMetaByAttribute("name", "twitter:description", description);
    ncSetMetaByAttribute("property", "og:title", title);
    ncSetMetaByAttribute("property", "og:description", description);
}

function ncObserveEntityNameForSeo() {
    const profile = ncGetDynamicSeoProfile();
    if (!profile || window.location.pathname.includes("/embed/")) return;

    const nameFromUrl = ncGetEntityNameFromUrl(profile);
    if (nameFromUrl) ncApplyDynamicEntitySeo(nameFromUrl);

    const usernameElement = document.getElementById("username");
    if (!usernameElement || typeof MutationObserver === "undefined") return;

    let lastName = "";
    const syncName = function() {
        const visibleName = ncCleanEntityName(usernameElement.textContent);
        if (!visibleName || visibleName === lastName) return;
        lastName = visibleName;
        ncApplyDynamicEntitySeo(visibleName);
    };

    const observer = new MutationObserver(syncName);
    observer.observe(usernameElement, { childList: true, characterData: true, subtree: true });
    syncName();
}

function ncSetMetaByAttribute(attribute, key, value) {
    if (!value) return;
    let element = document.head.querySelector('meta[' + attribute + '="' + key + '"]');
    if (!element) {
        element = document.createElement("meta");
        element.setAttribute(attribute, key);
        document.head.appendChild(element);
    }
    element.setAttribute("content", value);
}

function ncInjectFaqSchema(profile) {
    if (!profile || !Array.isArray(profile.faqs) || profile.faqs.length === 0) return;
    if (document.getElementById("nc-seo-faq-schema")) return;

    const schema = {
        "@context": "https://schema.org",
        "@type": "FAQPage",
        "mainEntity": profile.faqs.map(function(faq) {
            return {
                "@type": "Question",
                "name": faq[0],
                "acceptedAnswer": {
                    "@type": "Answer",
                    "text": faq[1]
                }
            };
        })
    };

    const script = document.createElement("script");
    script.id = "nc-seo-faq-schema";
    script.type = "application/ld+json";
    script.textContent = JSON.stringify(schema);
    document.head.appendChild(script);
}

